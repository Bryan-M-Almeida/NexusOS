#!/usr/bin/env python3
"""Generate build/assets.h and build/assets.bin for the NEXUS animations (src/intro.c).

Usage: mkassets.py <fonts_dir> <out.h> <out.bin>

- 4-bit alpha glyphs (4x supersampled) from Michroma (title/TEAM, one size per video
  mode) and JetBrains Mono (small text). Both fonts are OFL.
- Fixed-point tables: atan, cubic-bezier easing curves and a gaussian.
Requires Pillow (pip install pillow / apt install python3-pil).
"""
import math, sys, os
from PIL import Image, ImageDraw, ImageFont

fdir, out, out_bin = sys.argv[1:4]
MICHROMA = os.path.join(fdir, "Michroma-Regular.ttf")
MONO = os.path.join(fdir, "JetBrainsMono-Regular.ttf")
SS = 4  # supersampling

# Screen heights supported by the intro (must match MODES in intro.c)
HEIGHTS = (768, 600, 480)

# Placeholder bytes used in C strings for characters outside ASCII
REAL = {"~": "\u2026", "\x18": "\u2191", "\x19": "\u2193"}  # ellipsis, up/down arrows

# Status texts in all languages (uppercase letters only)
STATUS_CHARS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ~"
# Small font: acronym, boot log (kernel messages, uppercased) and selector hints
SMALL_CHARS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789&.,:;-+()/[]!~'%\x18\x19"
# Language selector options (Latin-1 bytes in C: \xCA = E circumflex, \xD1 = N tilde)
OPTION_CHARS = "".join(sorted(set("PORTUGU\u00caSENGLISHESPA\u00d1OL")))


def render_font(path, size, chars, name):
    """Render `chars` at `size` px (float) and return C source."""
    f = ImageFont.truetype(path, round(size * SS))
    asc, desc = f.getmetrics()
    data = bytearray()
    glyphs = []
    for ch in chars:
        real = REAL.get(ch, ch)
        pad = SS * 8
        w4 = int(f.getlength(real)) + 2 * pad
        h4 = asc + desc + 2 * pad
        w4 += -w4 % SS
        h4 += -h4 % SS
        im = Image.new("L", (w4, h4), 0)
        # pen and baseline on SS multiples so they stay aligned after downsampling
        base4 = pad + asc - asc % SS
        ImageDraw.Draw(im).text((pad, base4), real, font=f, fill=255, anchor="ls")
        sm = im.reduce(SS)
        bb = sm.getbbox()
        adv16 = round(f.getlength(real) / SS * 16)
        if bb is None:
            glyphs.append((len(data), 0, 0, 0, 0, adv16))
            continue
        x0, y0, x1, y1 = bb
        g = sm.crop(bb)
        w, h = g.size
        px = g.load()
        off = len(data)
        for y in range(h):
            row = [(px[x, y] * 15 + 127) // 255 for x in range(w)]
            if w % 2:
                row.append(0)
            for i in range(0, len(row), 2):
                data.append(row[i] | (row[i + 1] << 4))
        bx = x0 - pad // SS
        by = y0 - base4 // SS  # top relative to the baseline (negative = above)
        glyphs.append((off, w, h, bx, by, adv16))
    base = blob_add(data)
    c = [f"static const struct glyph {name}_g[{len(glyphs)}] = {{"]
    for gl in glyphs:
        c.append("    {%d, %d, %d, %d, %d, %d}," % gl)
    c.append("};")
    chars_c = "".join(c if 32 <= ord(c) < 127 and c not in '"\\' else "\\%03o" % ord(c) for c in chars)
    c.append(f'static const struct font {name} = {{{name}_g, {base}, "{chars_c}", '
             f"{round(size * 16)}, {round(asc / SS * 16)}, {round(desc / SS * 16)}}};")
    return "\n".join(c)


def bezier_table(x1, y1, x2, y2, n=256, scale=4096):
    def bx(t): return 3 * x1 * t * (1 - t) ** 2 + 3 * x2 * t * t * (1 - t) + t ** 3
    def by(t): return 3 * y1 * t * (1 - t) ** 2 + 3 * y2 * t * t * (1 - t) + t ** 3
    vals = []
    for i in range(n + 1):
        x = i / n
        lo, hi = 0.0, 1.0
        for _ in range(60):
            mid = (lo + hi) / 2
            if bx(mid) < x:
                lo = mid
            else:
                hi = mid
        vals.append(round(by((lo + hi) / 2) * scale))
    return vals


def table(name, ctype, vals):
    """Store a lookup table in the blob; the header exposes it as a flat-memory pointer."""
    size = {"u8": 1, "u16": 2}[ctype]
    off = blob_add(b"".join(v.to_bytes(size, "little") for v in vals))
    return f"#define {name} ((const __seg_fs {ctype} *)(asset_base + {off}))"


blob = bytearray()


def blob_add(data):
    """Append data to the asset blob (4-byte aligned) and return its offset."""
    global blob
    blob += bytes(-len(blob) % 4)
    off = ASSET_HDR + len(blob)
    blob += data
    return off


ASSET_HDR = 16  # "NXASSET1", u32 total size, u32 reserved

parts = ["/* Generated by tools/mkassets.py. Do not edit. */",
         "/* Fonts: Michroma and JetBrains Mono, SIL Open Font License 1.1 (tools/fonts/OFL-*.txt) */",
         "/* Bulk data lives in build/assets.bin, loaded from disk to asset_base at runtime. */"]

# atan(i/256) in 1/65536 turn units
parts.append(table("atan_tab", "u16", [round(math.atan(i / 256) / (2 * math.pi) * 65536) for i in range(257)]))
# easing: input index 0..256 (interpolated), output 0..4096
parts.append(table("ease_out_tab", "u16", bezier_table(0.16, 0.84, 0.24, 1)))   # var(--ease-out)
parts.append(table("ease_io_tab", "u16", bezier_table(0.42, 0, 0.58, 1)))       # ease-in-out
parts.append(table("ease_tab", "u16", bezier_table(0.25, 0.1, 0.25, 1)))        # CSS 'ease'
# gaussian exp(-x^2/2), x = i/64, 0..255
parts.append(table("gauss_tab", "u8", [round(255 * math.exp(-((i / 64) ** 2) / 2)) for i in range(256)]))

parts.append(render_font(MONO, 11.2, STATUS_CHARS, "fnt_mono_status"))  # 0.7rem
parts.append(render_font(MONO, 10.0, SMALL_CHARS, "fnt_mono_small"))  # max(10px, 1.9% of the ring)
parts.append(render_font(MICHROMA, 16.0, OPTION_CHARS, "fnt_option"))  # language selector
for H in HEIGHTS:
    D = H * 64 // 100  # ring diameter = 64% of height (same as intro.c)
    parts.append(render_font(MICHROMA, D * 0.078, "NEXUS.", f"fnt_title_{H}"))
    parts.append(render_font(MICHROMA, D * 0.13, "123", f"fnt_digit_{H}"))  # shutdown countdown
    parts.append(render_font(MICHROMA, D * 0.03, "TEAM", f"fnt_team_{H}"))

total = ASSET_HDR + len(blob)
parts.append(f"#define ASSET_SIZE {total}")
open(out, "w", newline="\n").write("\n\n".join(parts) + "\n")
open(out_bin, "wb").write(b"NXASSET1" + total.to_bytes(4, "little") + bytes(4) + blob)
print(f"{out}, {out_bin}: {total} bytes of asset data")
